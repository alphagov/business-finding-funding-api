alter table areas drop constraint areas_level_check;
alter table areas add constraint areas_level_check check (level in ('country', 'region', 'county', 'local-authority'));

alter table areas drop constraint areas_ons_code;
alter table areas add constraint areas_ons_code check (
  (level = 'country' and code ~ '^[ENSW]92000[0-9]{3}$') or
  (level = 'region' and code ~ '^E12[0-9]{6}$') or
  (level = 'county' and code ~ '^E10[0-9]{6}$') or
  (level = 'local-authority' and code ~ '^(E0[6-9]|W06|S12|N09)[0-9]{6}$')
);

