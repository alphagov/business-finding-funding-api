-- Some grants pay for both capital and revenue costs, so a scheme can have
-- more than one spend type. Nothing uses the single spend type yet.

alter table schemes drop column spend_type;

create table scheme_spend_types (
  scheme_id text references schemes (id) on update cascade on delete cascade,
  spend_type text references spend_types (code),
  primary key (scheme_id, spend_type)
);

